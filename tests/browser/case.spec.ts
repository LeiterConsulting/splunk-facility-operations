test('The case retains findings across decision and recovery, exports a customer brief, and restarts cleanly', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?vertical=retail&audience=executive&usecase=dependency');
  await expect(page.getByRole('region', { name: 'Operational story', exact: true })).toBeVisible();
  const alignment = await page.getByRole('navigation', { name: 'Workspace views', exact: true }).locator('[data-test="label"]').evaluateAll(labels => labels.map(label => label.getBoundingClientRect().left));
  expect(alignment.length).toBe(9);
  expect(Math.max(...alignment) - Math.min(...alignment)).toBeLessThan(1);
  await page.getByRole('button', { name: '3 Impact', exact: true }).click();
  await page.screenshot({ path: 'artifacts/browser-tests/case-impact.png', fullPage: false });
  await page.getByRole('button', { name: 'Explain this situation', exact: true }).click();
  await expect(page.getByLabel('Ask about the current operational context')).toHaveValue(/Finding, Supporting evidence/);
  await page.getByRole('button', { name: 'Investigate', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Investigation finding summary', exact: true })).toContainText('92.48%');
  await page.getByRole('button', { name: 'Change readiness', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Current operational case', exact: true })).toContainText('Investigation retained');
  await expect(page.getByLabel('Audience decision evidence')).toContainText('executive situation brief');
  await page.getByRole('button', { name: 'Defer decision', exact: true }).click();
  await page.getByRole('button', { name: 'Operations story', exact: true }).click();
  await page.getByRole('button', { name: '7 Verify', exact: true }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download customer brief', exact: true }).click();
  const brief = await readFile((await (await downloading).path())!, 'utf8');
  expect(brief).toContain('99.92%');
  expect(brief).toContain('92.48%');
  expect(brief).toContain('replay clock 90');
  expect(brief).toContain('Deferred for additional evidence');
  expect(brief).toContain('Customer proof-of-concept requirements');
  await page.getByRole('button', { name: 'Return to investigation', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Investigation finding summary', exact: true })).toContainText('92.48%');
  const exporting = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export evidence', exact: true }).click();
  expect(JSON.parse(await readFile((await (await exporting).path())!, 'utf8')).scope.clock).toBe(90);
  await page.getByRole('button', { name: 'Start guided walkthrough', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Current operational case', exact: true })).not.toContainText('Investigation retained');
  expect(errors).toEqual([]);
});

test('The short overview visits five stages without starting inference or inventing skipped evidence', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/?vertical=manufacturing&audience=ccb&usecase=change');
  await page.getByRole('button', { name: 'Start three-minute overview', exact: true }).click();
  const guide = page.getByRole('complementary', { name: 'Guided demo controls' });
  await expect(guide).toContainText('STEP 1 OF 5');
  for (const label of ['Business impact', 'Dependency', 'Decision', 'Verify']) await guide.getByRole('button', { name: 'Next: ' + label, exact: true }).click();
  const downloading = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download story evidence', exact: true }).click();
  const story = JSON.parse(await readFile((await (await downloading).path())!, 'utf8'));
  expect(story.visited_steps.map((step: { step: string }) => step.step)).toEqual(['baseline', 'impact', 'dependency', 'decision', 'verify']);
  expect(story.investigation).toBeNull();
  expect(story.decisions).toEqual([]);
  await guide.getByRole('button', { name: 'Finish walkthrough', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Presentation settings', exact: true }).click();
  await page.getByRole('button', { name: 'Clinical service interruption', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Industry / vertical', exact: true })).toHaveValue('distributed_care');
  await page.getByRole('button', { name: 'Apply presentation', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Operational story', exact: true })).toContainText('Clinical orders and results');
});

test('Navigating during a connected investigation preserves the running job and completed citations', async ({ page }) => {
  const now = Math.floor(Date.now() / 1000);
  const rows = demoSnapshot('retail', 'dependency', 90, now);
  const scope = { mode: 'demo', vertical: 'retail', usecase: 'dependency', audience: 'operations', clock: 90 };
  let complete = false, starts = 0, cancellations = 0;
  const html = await (await page.request.get('/')).body();
  await page.route('**/app/splunk_facility_operations/facility_operations*', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.route('**/facility_ops/settings*', route => route.fulfill({ json: { provider: 'openai', model: 'configured-model', can_configure: false } }));
  await page.route('**/search/jobs*', route => route.fulfill({ json: { results: rows } }));
  await page.route('**/facility_ops/agent*', route => {
    const payload = JSON.parse(new URLSearchParams(route.request().postData()!).get('payload')!);
    if (payload.operation === 'start') starts++;
    if (payload.operation === 'cancel') cancellations++;
    const job = { job_id: 'retained-case', created_at: now, activities: [], partial: '' };
    return route.fulfill({ json: complete ? { ...job, status: 'completed', result: { answer: 'Inspect [the access service](evidence:identity).', assessment: assessOperations(rows, now), generated_at: now, provider: 'openai', model: 'configured-model', scope, results: [{ kind: 'snapshot', rows }], trace: [] } } : { ...job, status: 'running' } });
  });
  await page.goto('/app/splunk_facility_operations/facility_operations?vertical=retail&usecase=dependency#investigate');
  await page.getByLabel('Ask about the current operational context').fill('Investigate the case');
  await page.getByRole('button', { name: 'Investigate', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Change readiness', exact: true }).click();
  complete = true;
  await expect(page.getByRole('region', { name: 'Current operational case', exact: true })).toContainText('Investigation retained');
  expect(starts).toBe(1);
  expect(cancellations).toBe(0);
  await page.getByRole('button', { name: 'Return to investigation', exact: true }).click();
  await page.getByRole('button', { name: 'the access service', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Cited component evidence', exact: true })).toContainText('Commerce access broker');
  await page.getByRole('button', { name: 'Live', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Return to investigation', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Cited component evidence', exact: true })).toHaveCount(0);
});
