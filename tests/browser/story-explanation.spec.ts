import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { demoSnapshot, demoHistory } from '../../src/model';

test('The walkthrough explains source chronology, query provenance, proposed response and authored recovery', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/?vertical=retail&audience=executive&usecase=dependency');
  await page.getByRole('button', { name: 'Start guided walkthrough', exact: true }).click();
  const guide = page.getByRole('complementary', { name: 'Guided demo controls' });
  await guide.getByRole('button', { name: 'Step 3: Business impact', exact: true }).click();
  const explanation = guide.getByRole('region', { name: 'Incident story explanation', exact: true });
  await expect(explanation).toContainText('640 to 3,960');
  await expect(explanation).toContainText('T+00:45');
  await expect(explanation).toContainText('T+01:30');
  await explanation.getByText('What was queried? · 2 searches', { exact: true }).click();
  await expect(explanation).toContainText('Local preview evaluation; SPL was not executed');
  await expect(explanation.locator('pre').last()).toContainText('where phase<=2');
  await explanation.getByText('How was it addressed?', { exact: true }).click();
  await expect(explanation.getByText(/No applied response has been returned/)).toBeVisible();
  await expect(guide.getByRole('button', { name: 'Next: Dependency', exact: true })).toBeInViewport();
  await guide.getByRole('button', { name: 'Step 7: Recover', exact: true }).click();
  await expect(explanation).toContainText('T+03:45');
  await expect(explanation.getByText(/DEMO-RESPONSE-RETAIL-DEPENDENCY-005/)).toBeVisible();
  await expect(explanation.getByText(/fictional team moves the client token route/)).toBeVisible();
  await expect(explanation).toContainText('partial recovery');
  await guide.getByRole('button', { name: 'Next: Verify', exact: true }).click();
  const download = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download story evidence', exact: true }).click();
  const story = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  const current = story.visited_steps.find((step: { step: string }) => step.step === 'verify');
  expect(current.narrative.events.map((event: { phase: number }) => event.phase)).toEqual([0, 1, 2, 3, 4, 5, 6]);
  expect(current.narrative.queries[1].rows).toBe(70);
  expect(current.timeline.search).toContain('where phase<=6');
  expect(story.decisions).toEqual([]);
  await page.screenshot({ path: 'artifacts/browser-tests/story-response.png', fullPage: false });
  await guide.getByRole('button', { name: 'Step 2: First signal', exact: true }).click();
  await explanation.getByText('How was it addressed?', { exact: true }).click();
  await expect(explanation.getByText(/No applied response has been returned/)).toBeVisible();
  await expect(explanation).not.toContainText('DEMO-RESPONSE-RETAIL-DEPENDENCY-005');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(guide.getByRole('button', { name: 'Next: Business impact', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('A failed chronology search blocks the stage, retries real receipts, and never starts inference', async ({ page }) => {
  const html = await (await page.request.get('/')).body();
  let fail = true;
  const queries: string[] = [];
  await page.route('**/app/splunk_facility_operations/facility_operations*', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.route('**/facility_ops/settings*', route => route.fulfill({ json: { provider: 'demo', can_configure: false } }));
  await page.route('**/search/jobs*', route => {
    const search = new URLSearchParams(route.request().postData()!).get('search')!;
    queries.push(search);
    const clock = Number(search.match(/facility_ops_demo_events\("retail","dependency",(\d+)\)/)![1]);
    if (search.includes('where phase<=') && clock === 90 && fail) return route.fulfill({ status: 503, json: { error: 'Chronology unavailable' } });
    const now = Math.floor(Date.now() / 1000);
    const rows = search.includes('where phase<=') ? demoHistory('retail', 'dependency', clock, now).filter(row => row.phase <= Math.floor(clock / 45)) : demoSnapshot('retail', 'dependency', clock, now);
    return route.fulfill({ json: { results: rows } });
  });
  let starts = 0;
  page.on('request', request => { if (request.url().includes('facility_ops/agent')) starts++; });
  await page.goto('/app/splunk_facility_operations/facility_operations?vertical=retail&usecase=dependency');
  await page.getByRole('button', { name: 'Start guided walkthrough', exact: true }).click();
  const guide = page.getByRole('complementary', { name: 'Guided demo controls' });
  await guide.getByRole('button', { name: 'Step 3: Business impact', exact: true }).click();
  await expect(guide.getByRole('alert')).toContainText('could not load');
  await expect(guide.getByRole('button', { name: 'Next: Dependency', exact: true })).toBeDisabled();
  await expect(guide.getByRole('region', { name: 'Incident story explanation', exact: true })).toHaveCount(0);
  fail = false;
  await guide.getByRole('button', { name: 'Retry stage search', exact: true }).click();
  const explanation = guide.getByRole('region', { name: 'Incident story explanation', exact: true });
  await expect(explanation).toContainText('T+01:30');
  await explanation.getByText('What was queried? · 2 searches', { exact: true }).click();
  await expect(explanation.getByRole('article').last()).toContainText('Executed in Splunk · 30 returned rows');
  expect(queries.some(query => query.includes('where phase<=2'))).toBe(true);
  expect(starts).toBe(0);
  await expect(guide.getByRole('button', { name: 'Next: Dependency', exact: true })).toBeEnabled();
});
