test('Installed stage transitions wait for matching evidence and running inference blocks advancement', async ({ page }) => {
  const html = await (await page.request.get('/')).body();
  let releaseImpact: (() => void) | undefined;
  let blockImpact = true;
  let starts = 0;
  await page.route('**/app/splunk_facility_operations/facility_operations*', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.route('**/facility_ops/settings*', route => route.fulfill({ json: { provider: 'openai', model: 'configured-model', key_configured: true, can_configure: false, allow_live_llm: false } }));
  await page.route('**/search/jobs*', async route => {
    const spl = new URLSearchParams(route.request().postData() ?? '').get('search')!;
    const clock = Number(spl.match(/facility_ops_demo_events\("retail","dependency",(\d+)\)/)![1]);
    if (clock === 90 && blockImpact) await new Promise<void>(resolve => { releaseImpact = resolve; });
    await route.fulfill({ json: { results: demoSnapshot('retail', 'dependency', clock, Math.floor(Date.now() / 1000)) } });
  });
  await page.route('**/facility_ops/agent*', async route => {
    const payload = JSON.parse(new URLSearchParams(route.request().postData() ?? '').get('payload')!);
    if (payload.operation === 'start') starts++;
    await route.fulfill({ status: 202, json: { job_id: 'guided-test', status: payload.operation === 'cancel' ? 'cancelled' : 'running', created_at: Math.floor(Date.now()/1000), activities: [] } });
  });
  await page.goto('/app/splunk_facility_operations/facility_operations?vertical=retail&usecase=dependency');
  await page.getByRole('button', { name: 'Start guided walkthrough', exact: true }).click();
  const guide = controls(page);
  await expect(guide.getByRole('button', { name: 'Next: First signal', exact: true })).toBeEnabled();
  await guide.getByRole('button', { name: 'Step 3: Business impact', exact: true }).click();
  await expect(guide.getByRole('button', { name: 'Next: Dependency', exact: true })).toBeDisabled();
  await expect(guide.getByLabel('Evidence for this step')).toHaveCount(0);
  await expect.poll(() => !!releaseImpact).toBe(true);
  blockImpact = false; releaseImpact!();
  await expect(guide).toContainText('2,286/2,472');
  await guide.getByRole('button', { name: 'Step 5: Investigate', exact: true }).click();
  expect(starts).toBe(0);
  await page.getByRole('button', { name: 'Investigate', exact: true }).click();
  await expect.poll(() => starts).toBe(1);
  await expect(guide.getByRole('button', { name: 'Next: Decision', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  await expect(guide.getByRole('button', { name: 'Next: Decision', exact: true })).toBeEnabled();
});
