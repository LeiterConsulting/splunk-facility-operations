import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { demoSnapshot } from '../../src/model';
const controls = (page: Page) => page.getByRole('complementary', { name: 'Guided demo controls' });

test('The default demo holds its baseline and walks through visible evidence, assistant and recovery', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.install();
  await page.goto('/?vertical=retail&audience=executive&usecase=dependency');
  await expect(page.getByRole('button', { name: '1 Normal', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.clock.fastForward(95000);
  await expect(page.getByRole('button', { name: '1 Normal', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Start guided walkthrough', exact: true }).click();
  const guide = controls(page);
  await expect(guide).toContainText('STEP 1 OF 8');
  await expect(page.locator('.fo-guide-highlight')).toBeInViewport({ ratio: 0.5 });
  await guide.getByRole('button', { name: 'Next: First signal', exact: true }).click();
  await expect(guide).toContainText('4,200');
  await expect(page.locator('.fo-guide-highlight')).toContainText('Commerce access broker');
  await guide.getByRole('button', { name: 'Next: Business impact', exact: true }).click();
  await expect(guide).toContainText('2,286/2,472');
  await expect(page.locator('.fo-guide-highlight')).toBeInViewport({ ratio: 0.5 });
  await guide.getByRole('button', { name: 'Next: Dependency', exact: true }).click();
  await expect(page).toHaveURL(/#dependencies$/);
  await expect(page.locator('.fo-guide-highlight').getByRole('button', { name: 'Commerce access broker, Critical, inspect evidence', exact: true })).toBeVisible();
  await expect(page.locator('.fo-guide-arrow')).toBeVisible();
  await guide.getByRole('button', { name: 'Next: Investigate', exact: true }).click();
  await expect(page.getByLabel('Ask about the current operational context')).toHaveValue(/query_events timeline/);
  await expect(page.getByText('Investigation steps', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Investigate', exact: true }).click();
  await expect(page.getByText('Investigation steps', { exact: true })).toBeVisible();
  await expect(page.locator('.fo-guide-highlight')).toHaveAttribute('data-demo-target', 'assistant-activity');
  await guide.getByRole('button', { name: 'Next: Decision', exact: true }).click();
  await expect(page.locator('.fo-guide-highlight')).toContainText('Confirm rollback');
  await expect(guide).toContainText('without approving or executing');
  await expect(page.getByText('Demo approval recorded', { exact: true })).toHaveCount(0);
  await guide.getByRole('button', { name: 'Next: Recover', exact: true }).click();
  await expect(guide).toContainText('98.18%');
  await guide.getByRole('button', { name: 'Next: Verify', exact: true }).click();
  await expect(guide).toContainText('99.92%');
  const downloading = page.waitForEvent('download');
  await guide.getByRole('button', { name: 'Download story evidence', exact: true }).click();
  const file = await downloading;
  const exported = JSON.parse(await readFile((await file.path())!, 'utf8'));
  expect(exported.synthetic).toBe(true);
  expect(exported.context.vertical).toBe('retail');
  expect(exported.visited_steps.map((s: { step: string }) => s.step)).toEqual(['baseline', 'signal', 'impact', 'dependency', 'assistant', 'decision', 'recovery', 'verify']);
  await guide.getByRole('button', { name: 'Restart story', exact: true }).click();
  await expect(guide).toContainText('STEP 1 OF 8');
  await guide.getByRole('button', { name: 'Exit guide', exact: true }).click();
  await expect(guide).toHaveCount(0);
  await expect(page.locator('.fo-guide-highlight,.fo-guide-arrow')).toHaveCount(0);
  expect(errors).toEqual([]);
});

